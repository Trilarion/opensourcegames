"""
Central place to calculate statistics about the entries. Used for updating the statistics.md file and the statistics page
of the website. Also renders statistics diagrams.
"""

import datetime
import io
import re
from collections import Counter
from collections.abc import Callable, Iterable, Mapping, Sequence

import matplotlib
import numpy as np
from matplotlib.figure import Figure

from osgl import osg

BASE_FIGURE_SIZE = 4

# fixed salt for the element ids of the SVG output, makes the output reproducible
SVG_HASH_SALT = 'osgl'

# code repositories on these sites count as popular (see create_statistics_markdown)
POPULAR_CODE_REPOSITORIES = ('github.com', 'gitlab.com', 'codeberg.org', 'code.sf.net')


def normalize_keyword(keyword: str) -> str:
    """
    Reduce variants of a keyword to their common form for counting.

    All multiplayer keywords (e.g. "multiplayer online + LAN") become "multiplayer". Content and "original required"
    keywords lose any text in parentheses.
    """
    if keyword.startswith('multiplayer'):
        return 'multiplayer'
    if keyword.startswith(('content', 'original required')):
        return re.sub(r'\(.*?\)\s*', '', keyword).strip()
    return str(keyword)


def get_field_statistics(
    entries: Iterable[Mapping], field: str, sub_field: str | None = None, include_na: bool = True,
    normalize: Callable[[str], str] | None = None,
) -> list[tuple[str, int]]:
    """
    Count how often each value of a field occurs in the given entries.

    :param entries: list of entries
    :param field: name of the field whose values are counted
    :param sub_field: if given, the field is looked up inside this sub field of each entry (e.g. 'Building')
    :param include_na: if true, entries without the field are counted as 'N/A'
    :param normalize: if given, applied to every value before counting (see normalize_keyword)
    :return: list of tuples (field value, occurrences) sorted by descending occurrences, then by name
    """
    counter = Counter()
    for entry in entries:
        if sub_field:
            entry = entry[sub_field]
        if field in entry:
            values = entry[field]
            counter.update(map(normalize, values) if normalize else values)
        elif include_na:
            counter['N/A'] += 1

    # highest occurrence first, then case-insensitive by name (the name itself as final tie-breaker)
    return sorted(counter.items(), key=lambda item: (-item[1], str.casefold(item[0]), item[0]))


def get_state_statistics(entries: Iterable[Mapping]) -> list[tuple[str, int]]:
    """
    Count the entries by development state (mature or beta) and activity (active or inactive).

    Each entry is counted exactly once. Entries that are neither mature nor beta are counted as 'N/A'.

    :param entries: list of entries
    :return: list of tuples (state, occurrences) in the fixed order mature/active, mature/inactive, beta/active,
        beta/inactive, followed by 'N/A' if there are such entries
    """
    counter = Counter()
    for entry in entries:
        state = entry['State']
        activity = 'inactive' if osg.is_inactive(entry) else 'active'
        if 'mature' in state:
            counter[f'mature, {activity}'] += 1
        elif 'beta' in state:
            counter[f'beta, {activity}'] += 1
        else:
            counter['N/A'] += 1

    statistics = [(name, counter[name]) for name in ('mature, active', 'mature, inactive', 'beta, active', 'beta, inactive')]
    if counter['N/A'] > 0:
        statistics.append(('N/A', counter['N/A']))
    return statistics


def _frequency_lines(stat: Sequence[tuple[str, int]], total: int) -> list[str]:
    """
    Format statistics as markdown list items with the occurrences in percent of ``total``.
    """
    return [f'- {name} ({count / total * 100:.1f}%)' for name, count in stat]


def _c_or_cpp(entry: Mapping) -> bool:
    """
    Return true if the entry is (partly) written in C or C++.
    """
    return 'C' in entry['Code language'] or 'C++' in entry['Code language']


def create_statistics_markdown(entries: Sequence[Mapping], date: datetime.datetime) -> str:
    """
    Create the content of the statistics.md file: frequencies of the values of several fields and lists of entries
    that could be improved.

    Frequencies are in percent of all mentions of a field (an entry can have several values), except for the platforms,
    which are in percent of all entries.

    :param entries: all entries
    :param date: time of the analysis, shown at the top
    :return: markdown text
    """
    number_entries = len(entries)
    fraction = lambda x: x / number_entries * 100  # conversion to percent of all entries

    text = '[comment]: # (autogenerated content, do not edit)\n# Statistics\n\n'
    text += f"analyzed {number_entries} entries on {date.strftime('%Y-%m-%d %H:%M:%S')}\n\n"

    # state (beta, mature, inactive)
    number_beta = sum(1 for entry in entries if 'beta' in entry['State'])
    number_mature = sum(1 for entry in entries if 'mature' in entry['State'])
    number_inactive = sum(1 for entry in entries if osg.is_inactive(entry))
    text += '## State\n\n'
    text += (f'- mature: {number_mature} ({fraction(number_mature):.1f}%)\n'
             f'- beta: {number_beta} ({fraction(number_beta):.1f}%)\n'
             f'- inactive: {number_inactive} ({fraction(number_inactive):.1f}%)\n\n')
    if number_inactive > 0:
        inactive = [(entry['Title'], osg.extract_inactive_year(entry)) for entry in entries if osg.is_inactive(entry)]
        inactive.sort(key=lambda x: str.casefold(x[0]))  # first sort by name
        inactive.sort(key=lambda x: x[1] or 0, reverse=True)  # then by inactive year (more recently first)
        text += '##### Inactive State\n\n' + ', '.join(f'{title} ({year})' for title, year in inactive) + '\n\n'

    # code languages, code licenses and keywords (in percent of all mentions)
    for heading, field, sub_heading, normalize in (
        ('Code Languages', 'Code language', 'Language frequency', None),
        ('Code licenses', 'Code license', 'Licenses frequency', None),
        ('Keywords', 'Keyword', 'Keywords frequency', normalize_keyword),
    ):
        stat = get_field_statistics(entries, field, include_na=False, normalize=normalize)
        total = sum(count for _, count in stat)
        text += f'## {heading}\n\n##### {sub_heading}\n\n' + '\n'.join(_frequency_lines(stat, total)) + '\n\n'

    # no download or play field
    titles = sorted((entry['Title'] for entry in entries if 'Download' not in entry and 'Play' not in entry), key=str.casefold)
    text += '## Entries without download or play fields\n\n' + f'{len(titles)}: ' + ', '.join(titles) + '\n\n'

    # code not hosted on a popular site (entries without code repository are included)
    titles = sorted((entry['Title'] for entry in entries
                     if not any(site in repo for repo in entry.get('Code repository', []) for site in POPULAR_CODE_REPOSITORIES)),
                    key=str.casefold)
    text += '## Entries with a code repository not on a popular site\n\n' + f'{len(titles)}: ' + ', '.join(titles) + '\n\n'

    # code dependencies
    field = 'Code dependency'
    number_with_field = sum(1 for entry in entries if field in entry)
    stat = get_field_statistics(entries, field, include_na=False)
    total = sum(count for _, count in stat)
    text += '## Code dependencies\n\n'
    text += f'With code dependency field {number_with_field} ({fraction(number_with_field):.1f}%)\n\n'
    text += '##### Code dependencies frequency\n\n' + '\n'.join(_frequency_lines(stat, total)) + '\n\n'

    # build systems (the availability is the number of mentions relative to the number of entries)
    field = 'Build system'
    stat = get_field_statistics(entries, field, sub_field='Building', include_na=False)
    total = sum(count for _, count in stat)
    text += '## Build systems\n\n'
    text += f'Build systems information available for {fraction(total):.1f}% of all projects.\n\n'
    text += f'##### Build systems frequency ({total})\n\n' + '\n'.join(_frequency_lines(stat, total)) + '\n\n'

    titles = sorted((entry['Title'] for entry in entries if field not in entry['Building'] and _c_or_cpp(entry)), key=str.casefold)
    text += f'##### C and C++ projects without build system information ({len(titles)})\n\n' + ', '.join(titles) + '\n\n'
    titles = sorted((entry['Title'] for entry in entries
                     if field in entry['Building'] and 'CMake' not in entry['Building'][field] and _c_or_cpp(entry)),
                    key=str.casefold)
    text += f'##### C and C++ projects with a build system different from CMake ({len(titles)})\n\n' + ', '.join(titles) + '\n\n'

    # platforms (in percent of all entries)
    field = 'Platform'
    number_with_field = sum(1 for entry in entries if field in entry)
    stat = get_field_statistics(entries, field, include_na=False)
    text += '## Platform\n\n'
    text += f'Platform information available for {fraction(number_with_field):.1f}% of all projects.\n\n'
    text += '##### Platforms frequency\n\n' + '\n'.join(_frequency_lines(stat, number_entries)) + '\n\n'

    return text


def truncate_stats(
    stat: Sequence[tuple[str, int]], threshold: int, name: str = 'Other',
) -> list[tuple[str, int]]:
    """
    Combine all items (value, count) with a count below the threshold into a single item.

    :param stat: statistics as returned by get_field_statistics
    :param threshold: items with a count below this value are combined
    :param name: name of the combined item
    :return: the items at or above the threshold (in the original order), followed by the combined item if any items
        were combined
    """
    kept = [item for item in stat if item[1] >= threshold]
    combined_count = sum(item[1] for item in stat if item[1] < threshold)
    if combined_count > 0:
        kept.append((name, combined_count))
    return kept


def _figure_to_svg(figure: Figure) -> str:
    """
    Render a figure as SVG text.

    The output is reproducible: the element ids use a fixed salt and the creation date is omitted, so the same chart
    always gives the same text.
    """
    buffer = io.StringIO()
    with matplotlib.rc_context({'svg.hashsalt': SVG_HASH_SALT}):
        figure.savefig(buffer, format='svg', transparent=True, metadata={'Date': None})
    return buffer.getvalue()


def export_pie_chart(stat: Sequence[tuple[str, int]]) -> str:
    """
    Create a pie chart of the given statistics and return it as SVG text.
    """
    labels = [item[0] for item in stat]
    sizes = [item[1] for item in stat]

    figure = Figure(figsize=(BASE_FIGURE_SIZE, BASE_FIGURE_SIZE), tight_layout=True)
    axes = figure.add_subplot()
    axes.pie(sizes, labels=labels, autopct='%1.1f%%', pctdistance=0.8, shadow=True, labeldistance=1.2, normalize=True)

    return _figure_to_svg(figure)


def export_bar_chart(stat: Sequence[tuple[str, int]], aspect_ratio: float = 1, tick_label_rotation: float = 0) -> str:
    """
    Create a bar chart of the given statistics and return it as SVG text.

    :param aspect_ratio: width of the figure relative to its height
    :param tick_label_rotation: rotation of the labels on the x axis in degrees
    """
    positions = np.arange(len(stat))
    labels = [item[0] for item in stat]
    heights = [item[1] for item in stat]

    figure = Figure(figsize=(aspect_ratio * BASE_FIGURE_SIZE, BASE_FIGURE_SIZE), tight_layout=True)
    axes = figure.add_subplot()
    bars = axes.bar(positions, heights, tick_label=labels, edgecolor='black')
    axes.bar_label(bars)
    axes.spines['top'].set_visible(False)
    axes.spines['right'].set_visible(False)
    axes.tick_params(axis='x', labelrotation=tick_label_rotation)

    return _figure_to_svg(figure)
