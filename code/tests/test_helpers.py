"""
Tests for small helper modules: archive folder names, repository name normalization and statistics.
"""

import datetime

import pytest

from osgl import archive, statistics
from osgl.external import github, gitlab


# Archive folder names (must be stable, otherwise the local archive gets cloned again)


@pytest.mark.parametrize('url, expected', [
    ('https://github.com/example/sample.git', 'github.example.sample.git'),
    ('https://gitlab.com/group/sub/project.git', 'gitlab.group.sub.project.git'),
    ('https://git.code.sf.net/p/game/code', 'sourceforge.game.code'),
    ('https://anongit.kde.org/game.git', 'kde.org.game.git'),
    ('https://example.org/repo.git', 'example.org.repo.git'),
    ('git://example.org/repo.git', 'example.org.repo.git'),
])
def test_git_folder_name(url, expected):
    """
    Known services are shortened, other URLs only lose their scheme, slashes become dots.
    """
    assert archive.git_folder_name(url) == expected


def test_derive_folder_name_malformed_url():
    """
    URLs without a known scheme are rejected.
    """
    with pytest.raises(RuntimeError, match='malformed url'):
        archive.derive_folder_name('example.org/repo', {})


# Repository names


@pytest.mark.parametrize('module, url', [
    (github, 'https://github.com/example/sample.git'),
    (gitlab, 'https://gitlab.com/example/sample.git'),
])
def test_normalize_repo_name(module, url):
    """
    Repository URLs are reduced to owner/name.
    """
    assert module.normalize_repo_name(url) == 'example/sample'
    assert module.normalize_repo_name('example/sample') == 'example/sample'


# Statistics


ENTRIES = [
    {'Code language': ['C', 'Lua'], 'Building': {'Build system': ['CMake']}},
    {'Code language': ['C'], 'Building': {}},
    {'Building': {'Build system': ['Make']}},
]


def test_get_field_statistics():
    """
    Values are counted, sorted by occurrence and then by name, missing fields count as N/A.
    """
    assert statistics.get_field_statistics(ENTRIES, 'Code language') == [('C', 2), ('Lua', 1), ('N/A', 1)]
    assert statistics.get_field_statistics(ENTRIES, 'Code language', include_na=False) == [('C', 2), ('Lua', 1)]


def test_get_field_statistics_sub_field():
    """
    Fields in a sub field (e.g. Building) can be evaluated.
    """
    stats = statistics.get_field_statistics(ENTRIES, 'Build system', sub_field='Building')
    assert stats == [('CMake', 1), ('Make', 1), ('N/A', 1)]


def test_truncate_stats():
    """
    Items below the threshold are combined into a single last item.
    """
    stats = [('C', 20), ('Lua', 3), ('Go', 2)]
    assert statistics.truncate_stats(stats, 10) == [('C', 20), ('Other', 5)]
    assert statistics.truncate_stats(stats, 1) == stats


@pytest.mark.parametrize('keyword, expected', [
    ('multiplayer online + LAN', 'multiplayer'),
    ('content open (some text)', 'content open'),
    ('original required (?)', 'original required'),
    ('role playing', 'role playing'),
])
def test_normalize_keyword(keyword, expected):
    """
    Multiplayer variants are merged, content keywords lose text in parentheses, others stay.
    """
    assert statistics.normalize_keyword(keyword) == expected


def test_get_field_statistics_normalize():
    """
    Values are normalized before they are counted.
    """
    entries = [{'Keyword': ['multiplayer online', 'action']}, {'Keyword': ['multiplayer LAN']}]
    assert statistics.get_field_statistics(entries, 'Keyword', normalize=statistics.normalize_keyword) == [
        ('multiplayer', 2), ('action', 1)]


def test_create_statistics_markdown():
    """
    The statistics file contains all sections, frequencies in percent and the lists of entries that could be improved.
    """
    entries = [
        {'Title': 'A', 'State': ['mature'], 'Keyword': ['action', 'multiplayer LAN'], 'Code language': ['C'],
         'Code license': ['MIT'], 'Code repository': ['https://github.com/a/a.git'], 'Download': ['x'],
         'Platform': ['Linux'], 'Building': {'Build system': ['Make']}},
        {'Title': 'B', 'State': ['beta', 'inactive since 2015'], 'Keyword': ['puzzle'], 'Code language': ['Lua'],
         'Code license': ['MIT'], 'Code repository': ['https://example.org/b.git'], 'Building': {}},
    ]
    text = statistics.create_statistics_markdown(entries, datetime.datetime(2026, 1, 2, 3, 4, 5))
    assert text.startswith('[comment]: # (autogenerated content, do not edit)\n# Statistics\n\n'
                           'analyzed 2 entries on 2026-01-02 03:04:05\n\n')
    assert '- mature: 1 (50.0%)\n- beta: 1 (50.0%)\n- inactive: 1 (50.0%)\n\n##### Inactive State\n\nB (2015)\n\n' in text
    assert '##### Language frequency\n\n- C (50.0%)\n- Lua (50.0%)\n\n' in text
    assert '- multiplayer (33.3%)' in text
    assert '## Entries without download or play fields\n\n1: B\n\n' in text
    assert '## Entries with a code repository not on a popular site\n\n1: B\n\n' in text
    assert '##### C and C++ projects with a build system different from CMake (1)\n\nA\n\n' in text
    assert 'Platform information available for 50.0% of all projects.\n\n##### Platforms frequency\n\n- Linux (50.0%)\n\n' in text


def test_get_state_statistics():
    """
    Each entry is counted once by state and activity in a fixed order, entries without mature or beta count as N/A.
    """
    entries = [{'State': ['mature']}, {'State': ['mature', 'inactive since 2010']}, {'State': ['beta']},
               {'State': ['beta']}, {'State': ['beta', 'inactive since 2020']}]
    assert statistics.get_state_statistics(entries) == [
        ('mature, active', 1), ('mature, inactive', 1), ('beta, active', 2), ('beta, inactive', 1)]
    entries.append({'State': ['inactive since 2000']})
    assert statistics.get_state_statistics(entries)[-1] == ('N/A', 1)


def test_get_field_statistics_ties_sorted_by_name():
    """
    Values with the same number of occurrences are sorted case-insensitively by name.
    """
    entries = [{'Code language': ['b', 'A', 'C']}]
    assert statistics.get_field_statistics(entries, 'Code language') == [('A', 1), ('b', 1), ('C', 1)]


@pytest.mark.parametrize('export', [statistics.export_pie_chart, statistics.export_bar_chart])
def test_export_charts(export):
    """
    Charts are returned as SVG text.
    """
    text = export([('C', 2), ('Lua', 1)])
    assert text.lstrip().startswith('<?xml')
    assert '<svg' in text


@pytest.mark.parametrize('export', [statistics.export_pie_chart, statistics.export_bar_chart])
def test_export_charts_reproducible(export):
    """
    The same statistics always give the same SVG text (no random ids, no creation date).
    """
    stat = [('C', 2), ('Lua', 1)]
    text = export(stat)
    assert export(stat) == text
    assert '<dc:date>' not in text
