"""
Tests for the developer and inspiration listings (grammars/listing.lark, reading, validating and writing).
"""

import lark
import pytest

from osgl import constants as c, osg, utils as u


DEVELOPERS = """[comment]: # (partly autogenerated content, edit with care, read the manual before)
# Developer [2]

## Jane Doe [2]

- Games: Game A, "Game, B"
- Home: https://example.org

## John [1]

- Games: Game C
"""

INSPIRATIONS = """[comment]: # (partly autogenerated content, edit with care, read the manual before)
# Inspirations [1]

## Master of Orion [2]

- Inspired entries: Game A, Game B
- Media: https://en.wikipedia.org/wiki/Master_of_Orion

"""


@pytest.fixture
def developers_file(tmp_path, monkeypatch):
    """
    Redirects the developers file to a temporary file and returns a function that writes content to it.
    """
    file = tmp_path / 'developers.md'
    monkeypatch.setattr(c, 'developer_file', file)

    def write(content):
        """
        Writes the given content to the temporary developers file.
        """
        file.write_text(content, encoding='utf-8')

    return write


@pytest.fixture
def inspirations_file(tmp_path, monkeypatch):
    """
    Redirects the inspirations file to a temporary file and returns a function that writes content to it.
    """
    file = tmp_path / 'inspirations.md'
    monkeypatch.setattr(c, 'inspirations_file', file)

    def write(content):
        """
        Writes the given content to the temporary inspirations file.
        """
        file.write_text(content, encoding='utf-8')

    return write


# Grammar


def test_listing_grammar(parse_listing):
    """
    Each listing entry becomes a dictionary with the name and the properties as lists of values.
    """
    developers = parse_listing(DEVELOPERS)
    assert developers == [
        {'Name': 'Jane Doe', 'Games': ['Game A', 'Game, B'], 'Home': ['https://example.org']},
        {'Name': 'John', 'Games': ['Game C']},
    ]


def test_listing_grammar_duplicate_key(parse_listing):
    """
    A property must not appear twice in a listing entry.
    """
    text = DEVELOPERS.replace('- Games: Game C\n', '- Games: Game C\n- Games: Game D\n')
    with pytest.raises(lark.exceptions.VisitError, match='Key in entry appears twice'):
        parse_listing(text)


def test_listing_grammar_requires_header(parse_listing):
    """
    The comment line and the header are required.
    """
    text = DEVELOPERS.split('\n', 2)[2]
    with pytest.raises(lark.exceptions.LarkError):
        parse_listing(text)


# Reading and validating developers


def test_read_developers(developers_file):
    """
    Developers are returned as dictionary by name.
    """
    developers_file(DEVELOPERS)
    developers = osg.read_developers()
    assert list(developers.keys()) == ['Jane Doe', 'John']
    assert developers['John']['Games'] == ['Game C']


def test_developer_missing_essential_field(developers_file):
    """
    Every developer needs the essential fields.
    """
    developers_file(DEVELOPERS.replace('- Games: Game C\n', '- Home: https://example.com\n'))
    with pytest.raises(RuntimeError, match='Essential field "Games" missing in developer John'):
        osg.read_developers()


def test_developer_invalid_field(developers_file):
    """
    Only valid developer fields may be used.
    """
    developers_file(DEVELOPERS.replace('- Games: Game C\n', '- Games: Game C\n- Twitter: @john\n'))
    with pytest.raises(RuntimeError, match='Invalid field "Twitter" in developer John'):
        osg.read_developers()


def test_developer_invalid_url(developers_file):
    """
    URL fields must contain http(s) URLs.
    """
    developers_file(DEVELOPERS.replace('https://example.org', 'example.org'))
    with pytest.raises(RuntimeError, match='Invalid URL in field "Home" in developer Jane Doe'):
        osg.read_developers()


def test_write_developers(developers_file):
    """
    Developers are written sorted by name, with games first and values sorted and deduplicated.
    """
    developers_file(DEVELOPERS)
    developers = {
        'Zed': {'Name': 'Zed', 'Games': ['b', 'A', 'b'], 'Home': ['https://zed.org']},
        'Anna': {'Name': 'Anna', 'Games': ['Game, X']},
    }
    osg.write_developers(developers)
    text = u.read_text(c.developer_file)
    assert text == (f'{c.generic_comment_string}\n# Developer [2]\n\n'
                    '## Anna [1]\n\n- Games: "Game, X"\n\n'
                    '## Zed [3]\n\n- Games: A, b\n- Home: https://zed.org\n\n')


# Reading and validating inspirations


def test_read_inspirations(inspirations_file):
    """
    Inspirations are returned as dictionary by name.
    """
    inspirations_file(INSPIRATIONS)
    inspirations = osg.read_inspirations()
    assert inspirations['Master of Orion']['Inspired entries'] == ['Game A', 'Game B']


def test_inspiration_duplicate_name(inspirations_file):
    """
    Inspiration names must be unique.
    """
    inspirations_file(INSPIRATIONS + INSPIRATIONS.split('\n', 3)[3])
    with pytest.raises(RuntimeError, match='Duplicate inspiration names: Master of Orion'):
        osg.read_inspirations()


def test_inspiration_invalid_field(inspirations_file):
    """
    Only valid inspiration fields may be used.
    """
    inspirations_file(INSPIRATIONS.replace('- Media:', '- Home:'))
    with pytest.raises(RuntimeError, match='Invalid field "Home" in inspiration Master of Orion'):
        osg.read_inspirations()


def test_inspiration_invalid_url(inspirations_file):
    """
    URL fields must contain http(s) URLs.
    """
    inspirations_file(INSPIRATIONS.replace('https://en.wikipedia', 'en.wikipedia'))
    with pytest.raises(RuntimeError, match='Invalid URL in field "Media" in inspiration Master of Orion'):
        osg.read_inspirations()


def test_inspirations_write_read_roundtrip(inspirations_file):
    """
    Written inspirations are read back unchanged.
    """
    inspirations_file(INSPIRATIONS)
    inspirations = osg.read_inspirations()
    osg.write_inspirations(inspirations)
    assert u.read_text(c.inspirations_file) == INSPIRATIONS


